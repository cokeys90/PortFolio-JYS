/**
 * 시작일 기준 최신순 정렬 (YYYY-MM 문자열 비교).
 * 같은 시작일이면 이름 순으로 안정 정렬.
 */
export const sortedProjects = [...projects].sort((a, b) => {
  const cmp = b.startedAt.localeCompare(a.startedAt)
  return cmp !== 0 ? cmp : a.name.localeCompare(b.name)
})

